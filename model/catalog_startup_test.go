	db := catalogStartupDB(t, "sqlite")
	require.NoError(t, db.AutoMigrate(&Option{}))
	require.NoError(t, db.Create(&[]Option{{Key: "theme.frontend", Value: "classic"}, {Key: "FAQ", Value: `[{"question":"kept","answer":"kept"}]`}}).Error)
