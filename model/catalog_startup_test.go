func catalogStartupDB(t *testing.T, dialect string) *gorm.DB {
	t.Helper()
	dsn := "local"
	if dialect == "mysql" {
		dsn = os.Getenv("TEST_MYSQL_DSN")
	}
	if dialect == "postgres" {
		dsn = os.Getenv("TEST_POSTGRES_DSN")
	}
	if dsn == "" {
		t.Skip("dedicated test database is not configured")
	}
	oldDB, oldLog, oldMaster, oldPath := DB, LOG_DB, common.IsMasterNode, common.SQLitePath
	oldType, oldLogType := common.MainDatabaseType(), common.LogDatabaseType()
	t.Cleanup(func() {
		DB, LOG_DB, common.IsMasterNode, common.SQLitePath = oldDB, oldLog, oldMaster, oldPath
		common.SetDatabaseTypes(oldType, oldLogType)
		initCol()
	})
	t.Setenv("SQL_DSN", dsn)
	t.Setenv("LOG_SQL_DSN", "")
	t.Setenv("SKIP_64BIT_QUOTA_SCHEMA_CHECK", "false")
	common.SQLitePath = filepath.Join(t.TempDir(), "startup.db")
	db, kind, err := chooseDB("SQL_DSN", false)
	require.NoError(t, err)
	DB = db
	common.SetMainDatabaseType(kind)
	common.SetLogDatabaseType(kind)
	initCol()
	common.IsMasterNode = true
	for _, value := range CatalogIntegrationModels() {
		require.NoError(t, db.Migrator().DropTable(value))
	}
	t.Cleanup(func() {
		for _, value := range CatalogIntegrationModels() {
			require.NoError(t, db.Migrator().DropTable(value))
		}
		sqlDB, err := db.DB()
		require.NoError(t, err)
		require.NoError(t, sqlDB.Close())
	})
	return db
}

func TestCatalogPostgresIdentityAndSequencePermissions(t *testing.T) {
	db := catalogStartupDB(t, "postgres")
	const role = "dtff_catalog_insert_role"
	require.NoError(t, db.Exec("CREATE ROLE "+role).Error)
	t.Cleanup(func() {
		require.NoError(t, db.Exec("DROP TABLE IF EXISTS pk_role_serial, pk_role_identity").Error)
		require.NoError(t, db.Exec("DROP OWNED BY "+role).Error)
		require.NoError(t, db.Exec("DROP ROLE "+role).Error)
	})
	require.NoError(t, db.Table("pk_role_serial").AutoMigrate(&struct {
		ID int `gorm:"primaryKey"`
	}{}))
	require.NoError(t, db.Exec("CREATE TABLE pk_role_identity (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY)").Error)
	require.NoError(t, db.Exec("GRANT USAGE ON SCHEMA public TO "+role).Error)
	require.NoError(t, db.Exec("GRANT SELECT,INSERT ON pk_role_serial,pk_role_identity TO "+role).Error)
	rollback := errors.New("test rollback")
	for _, table := range []string{"pk_role_serial", "pk_role_identity"} {
		err := db.Transaction(func(tx *gorm.DB) error {
			require.NoError(t, tx.Exec("SET LOCAL ROLE "+role).Error)
			exists, valid, err := catalogPrimaryKeyState(tx, table)
			require.NoError(t, err)
			require.True(t, exists)
			var id int
			insertErr := tx.Raw("INSERT INTO " + table + " DEFAULT VALUES RETURNING id").Scan(&id).Error
			if table == "pk_role_identity" {
				require.True(t, valid)
				require.NoError(t, insertErr)
				require.Positive(t, id)
			} else {
				require.False(t, valid)
				require.Error(t, insertErr)
			}
			return rollback
		})
		require.ErrorIs(t, err, rollback)
	}
	var sequence string
	require.NoError(t, db.Raw("SELECT pg_get_serial_sequence('pk_role_serial','id')").Scan(&sequence).Error)
	require.NoError(t, db.Exec("GRANT USAGE ON SEQUENCE "+sequence+" TO "+role).Error)
	require.ErrorIs(t, db.Transaction(func(tx *gorm.DB) error {
		require.NoError(t, tx.Exec("SET LOCAL ROLE "+role).Error)
		_, valid, err := catalogPrimaryKeyState(tx, "pk_role_serial")
		require.NoError(t, err)
		require.True(t, valid)
		var id int
		require.NoError(t, tx.Raw("INSERT INTO pk_role_serial DEFAULT VALUES RETURNING id").Scan(&id).Error)
		require.Positive(t, id)
		return rollback
	}), rollback)
	require.NoError(t, db.Exec("ALTER TABLE pk_role_serial ALTER COLUMN id SET DEFAULT 0").Error)
	_, valid, err := catalogPrimaryKeyState(db, "pk_role_serial")
	require.NoError(t, err)
	require.False(t, valid)
}

