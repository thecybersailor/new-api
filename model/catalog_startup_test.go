func TestCatalogSQLiteGeneratedPrimaryKeyShapes(t *testing.T) {
	db := catalogStartupDB(t, "sqlite")
	for _, tc := range []struct {
		name, definition string
		valid            bool
	}{
		{"rowid", "id INTEGER PRIMARY KEY", true},
		{"autoincrement", "id INTEGER PRIMARY KEY AUTOINCREMENT", true},
		{"table_desc", "id INTEGER, PRIMARY KEY(id DESC)", true},
		{"bigint", "id BIGINT PRIMARY KEY", false},
		{"int", "id INT PRIMARY KEY", false},
		{"column_desc", "id INTEGER PRIMARY KEY DESC", false},
		{"composite", "id INTEGER, other INTEGER, PRIMARY KEY(id,other)", false},
	} {
		t.Run(tc.name, func(t *testing.T) {
			require.NoError(t, db.Exec("CREATE TABLE pk_shape ("+tc.definition+")").Error)
			exists, valid, err := catalogPrimaryKeyState(db, "pk_shape")
			require.NoError(t, err)
			require.True(t, exists)
			require.Equal(t, tc.valid, valid)
			require.NoError(t, db.Exec("DROP TABLE pk_shape").Error)
		})
	}
	require.NoError(t, db.Exec("CREATE TABLE pk_shape (id INTEGER PRIMARY KEY) WITHOUT ROWID").Error)
	_, valid, err := catalogPrimaryKeyState(db, "pk_shape")
	require.NoError(t, err)
	require.False(t, valid)
}

